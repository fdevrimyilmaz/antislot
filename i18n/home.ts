export function getHomeLocale(language: Language): HomeLocale {
  return HOME_LOCALES[language] ?? HOME_LOCALES.en;
}

export function getTodayLocale(language: Language): TodayLocale {
  return TODAY_LOCALES[language] ?? TODAY_LOCALES.en;
}

export function getStreakLocale(language: Language): StreakLocale {
  return STREAK_LOCALES[language] ?? STREAK_LOCALES.en;
}

export function getInsightsLocale(language: Language): InsightsLocale {
  return INSIGHTS_LOCALES[language] ?? INSIGHTS_LOCALES.en;
}

export function getLocaleTag(language: Language): string {
  return LANGUAGE_LOCALE_TAGS[language] ?? LANGUAGE_LOCALE_TAGS.en;
}

export function formatLocaleTemplate(
  template: string,
  values: Record<string, string | number>
): string {
  return Object.entries(values).reduce((acc, [key, value]) => {
    return acc.replaceAll(`{${key}}`, String(value));
  }, template);
}

